  START_TIME BIGINT NOT NULL, END_TIME BIGINT, CALENDAR_NAME VARCHAR(190), MISFIRE_INSTR SMALLINT,
  JOB_DATA BLOB, PRIMARY KEY (SCHED_NAME,TRIGGER_NAME,TRIGGER_GROUP),
  INDEX IDX_QRTZ_T_J (SCHED_NAME,JOB_NAME,JOB_GROUP), INDEX IDX_QRTZ_T_STATE (SCHED_NAME,TRIGGER_STATE),
  INDEX IDX_QRTZ_T_NEXT_FIRE_TIME (SCHED_NAME,NEXT_FIRE_TIME)
);
