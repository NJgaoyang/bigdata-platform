CREATE TABLE IF NOT EXISTS workflow_definition_version (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    workflow_code VARCHAR(128) NOT NULL,
    workflow_name VARCHAR(128) NOT NULL,
    version_no INT NOT NULL,
    definition_json LONGTEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PUBLISHED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_workflow_definition_version (workflow_code, version_no)
);

CREATE TABLE IF NOT EXISTS workflow_instance (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    instance_code VARCHAR(64) NOT NULL UNIQUE,
    workflow_code VARCHAR(128) NOT NULL,
    definition_version INT NOT NULL,
    run_type VARCHAR(32) NOT NULL DEFAULT 'MANUAL',
    status VARCHAR(32) NOT NULL,
    parameters_json TEXT,
    started_at TIMESTAMP NULL,
    finished_at TIMESTAMP NULL,
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_workflow_instance_code_status (workflow_code, status),
    INDEX idx_workflow_instance_created (created_at)
);

CREATE TABLE IF NOT EXISTS task_instance (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    workflow_instance_id BIGINT NOT NULL,
    node_id BIGINT NOT NULL,
    node_name VARCHAR(128) NOT NULL,
    node_type VARCHAR(32) NOT NULL,
    attempt_no INT NOT NULL DEFAULT 1,
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMP NULL,
    finished_at TIMESTAMP NULL,
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_task_instance_workflow (workflow_instance_id, status)
);

CREATE TABLE IF NOT EXISTS task_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    task_instance_id BIGINT NOT NULL,
    log_level VARCHAR(16) NOT NULL DEFAULT 'INFO',
    message LONGTEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_task_log_task (task_instance_id, id)
);

CREATE TABLE IF NOT EXISTS scheduler_trigger (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    trigger_code VARCHAR(128) NOT NULL UNIQUE,
    workflow_code VARCHAR(128) NOT NULL,
    cron_expression VARCHAR(128) NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    failure_strategy VARCHAR(32) NOT NULL DEFAULT 'END',
    parallelism INT NOT NULL DEFAULT 1,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS QRTZ_JOB_DETAILS (
  SCHED_NAME VARCHAR(120) NOT NULL, JOB_NAME VARCHAR(190) NOT NULL, JOB_GROUP VARCHAR(190) NOT NULL,
  DESCRIPTION VARCHAR(250), JOB_CLASS_NAME VARCHAR(250) NOT NULL, IS_DURABLE VARCHAR(1) NOT NULL,
  IS_NONCONCURRENT VARCHAR(1) NOT NULL, IS_UPDATE_DATA VARCHAR(1) NOT NULL, REQUESTS_RECOVERY VARCHAR(1) NOT NULL,
  JOB_DATA BLOB, PRIMARY KEY (SCHED_NAME,JOB_NAME,JOB_GROUP)
);
CREATE TABLE IF NOT EXISTS QRTZ_TRIGGERS (
  SCHED_NAME VARCHAR(120) NOT NULL, TRIGGER_NAME VARCHAR(190) NOT NULL, TRIGGER_GROUP VARCHAR(190) NOT NULL,
  JOB_NAME VARCHAR(190) NOT NULL, JOB_GROUP VARCHAR(190) NOT NULL, DESCRIPTION VARCHAR(250), NEXT_FIRE_TIME BIGINT,
